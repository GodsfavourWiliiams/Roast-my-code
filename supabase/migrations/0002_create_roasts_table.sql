create table if not exists roasts (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  repo_id bigint references repositories(id) on delete cascade not null,
  pr_number integer,
  pr_title text,
  roast_content text not null,
  roast_score integer check (roast_score >= 0 and roast_score <= 10),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table roasts enable row level security;

create policy "Users can view their own roasts"
  on roasts for select
  using ( auth.uid() = user_id );

create policy "Users can insert their own roasts"
  on roasts for insert
  with check ( auth.uid() = user_id );

create policy "Users can delete their own roasts"
  on roasts for delete
  using ( auth.uid() = user_id );
